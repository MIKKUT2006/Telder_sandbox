using System;

namespace Game.World.Generation
{
    [Serializable]
    public class CaveSettings
    {

        // =====================================================
        // DEPTH
        // =====================================================

        // Минимальная глубина, на которой могут появляться
        // обычные пещеры.
        //
        // Например:
        // Surface = 100
        // StartDepth = 18
        //
        // Первые обычные пещеры могут начинаться примерно
        // с Y = 82.
        public int StartDepth;


        // Защита поверхности.
        //
        // Не даёт обычному шуму сразу вырезать огромную
        // полость возле поверхности.
        //
        // Входы в пещеры генерируются отдельно.
        public int SurfaceProtectionDepth;


        // =====================================================
        // GENERAL DENSITY
        // =====================================================

        // Общая плотность пещер.
        //
        // ВАЖНО:
        // Это не процент пустых блоков.
        //
        // Это множитель количества пещерных структур.
        public float CaveDensity;


        // =====================================================
        // TUNNELS
        // =====================================================

        // Размер сетки, по которой появляются центры
        // тоннельных систем.
        //
        // Меньше = тоннельных систем больше.
        // Больше = тоннельных систем меньше.
        public float TunnelRegionSize;


        // Вероятность появления тоннельной системы
        // в одной области.
        //
        // 0.0 = нет тоннелей.
        // 1.0 = тоннели почти в каждой области.
        public float TunnelSpawnChance;


        // Средняя длина тоннеля.
        public float TunnelLength;


        // Случайное отклонение длины тоннеля.
        public float TunnelLengthVariation;


        // Минимальный радиус тоннеля.
        //
        // При значениях 1.5-2.0 получаем проходы
        // примерно 3-4 блока шириной.
        public float TunnelRadiusMin;


        // Максимальный радиус тоннеля.
        //
        // 2.5-3.0 даёт тоннели примерно 5-6 блоков.
        public float TunnelRadiusMax;


        // Насколько сильно тоннель может менять направление.
        //
        // Больше = более извилистые тоннели.
        public float TunnelWander;


        // Частота изменения направления тоннеля.
        public float TunnelWanderScale;


        // =====================================================
        // ROOMS
        // =====================================================

        // Размер области, в которой могут появляться комнаты.
        //
        // Больше = комнаты реже.
        public float RoomRegionSize;


        // Вероятность появления комнаты.
        public float RoomSpawnChance;


        // Минимальный радиус комнаты.
        public float RoomRadiusMin;


        // Максимальный радиус комнаты.
        public float RoomRadiusMax;


        // Насколько комната может быть вытянута
        // по горизонтали.
        public float RoomStretchX;


        // Насколько комната может быть вытянута
        // по вертикали.
        public float RoomStretchY;


        // Сила неровности стен комнаты.
        //
        // 0 = идеальный круг.
        // 0.2-0.4 = естественная форма.
        public float RoomWarpStrength;


        // Масштаб неровности стен комнаты.
        public float RoomWarpScale;


        // =====================================================
        // CAVE CONNECTIONS
        // =====================================================

        // Вероятность соединения комнаты с тоннельной системой.
        public float RoomConnectionChance;


        // =====================================================
        // SURFACE ENTRANCES
        // =====================================================

        // Разрешены ли входы на поверхность.
        public bool EnableSurfaceEntrances;


        // Вероятность входа в каждой подходящей области.
        //
        // Должна быть маленькой.
        public float SurfaceEntranceChance;


        // Минимальная глубина обычной пещеры,
        // из которой может начинаться вход.
        public int SurfaceEntranceDepth;


        // Радиус верхней части входа.
        public float EntranceRadius;


        // Ширина вертикального/наклонного тоннеля входа.
        public float EntranceTunnelRadius;


        // Длина входного тоннеля.
        public float EntranceTunnelLength;


        // Сила отклонения входа в сторону.
        public float EntranceWander;


        // =====================================================
        // SMALL DETAILS
        // =====================================================

        // Дополнительный шум для стен.
        //
        // Используется только для изменения формы,
        // а не для создания огромных пещер.
        public float DetailScale;


        public float DetailStrength;


        // =====================================================
        // CONSTRUCTOR
        // =====================================================

        public CaveSettings()
        {

            // =================================================
            // DEPTH
            // =================================================

            StartDepth =
                18;

            SurfaceProtectionDepth =
                14;


            // =================================================
            // DENSITY
            // =================================================

            // Много пещерных систем.
            CaveDensity =
                1.0f;


            // =================================================
            // TUNNELS
            // =================================================

            TunnelRegionSize =
                55f;

            TunnelSpawnChance =
                0.8f;

            TunnelLength =
                40f;

            TunnelLengthVariation =
                15f;

            TunnelRadiusMin =
               2.5f;

            TunnelRadiusMax =
                15f;

            TunnelWander =
                60f;

            TunnelWanderScale =
                0.8f;


            // =================================================
            // ROOMS
            // =================================================

            RoomRegionSize =
                120f;

            RoomSpawnChance =
                0.32f;

            RoomRadiusMin =
                7f;

            RoomRadiusMax =
                15f;

            RoomStretchX =
                3f;

            RoomStretchY =
                3.5f;

            RoomWarpStrength =
                0.9f;

            RoomWarpScale =
                0.3f;


            // =================================================
            // CONNECTIONS
            // =================================================

            RoomConnectionChance =
                0.95f;


            // =================================================
            // SURFACE ENTRANCES
            // =================================================

            EnableSurfaceEntrances =
                true;

            SurfaceEntranceChance =
                0.08f;

            SurfaceEntranceDepth =
                18;

            EntranceRadius =
                2.5f;

            EntranceTunnelRadius =
                2.0f;

            EntranceTunnelLength =
                35f;

            EntranceWander =
                12f;


            // =================================================
            // DETAILS
            // =================================================

            DetailScale =
                0.02f;

            DetailStrength =
                0.27f;

        }

    }
}