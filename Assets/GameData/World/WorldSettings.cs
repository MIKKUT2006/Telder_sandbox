using System;


namespace Game.World
{

    public class WorldSettings
    {

        // =====================================================
        // WORLD
        // =====================================================

        // Seed мира.
        // Определяет весь процедурно сгенерированный мир.
        public int Seed;


        // Размер чанка по X и Y.
        public int ChunkSize;


        // Радиус загрузки чанков вокруг игрока.
        public int ViewDistance;


        // Полная высота процедурно генерируемого мира
        // в блоках.
        public int WorldHeight;


        // Название мира.
        public string WorldName;


        // =====================================================
        // WORLD VERTICAL BOUNDS
        // =====================================================

        // Базовый уровень поверхности мира.
        //
        // Это НЕ реальная поверхность каждого столбца.
        //
        // Это центральный уровень,
        // относительно которого строится мир.
        public int SurfaceHeight;


        // Нижняя граница мира.
        //
        // Вычисляется автоматически.
        public int BottomWorldY
        {
            get
            {
                return
                    SurfaceHeight -
                    WorldHeight +
                    1;
            }
        }


        // =====================================================
        // TERRAIN
        // =====================================================

        // Высота крупных холмов.
        public int HillHeight;


        // Масштаб крупных холмов.
        public float HillScale;


        // Высота средних неровностей.
        public int TerrainVariation;


        // Масштаб средних неровностей.
        public float TerrainScale;


        // Высота мелких неровностей.
        public int TerrainDetail;


        // Масштаб мелких неровностей.
        public float TerrainDetailScale;


        // =====================================================
        // CONSTRUCTOR
        // =====================================================

        public WorldSettings()
        {

            // -------------------------------------------------
            // WORLD
            // -------------------------------------------------

            ChunkSize =
                32;


            ViewDistance =
                5;


            WorldHeight =
                256;


            WorldName =
                "New World";


            Seed =
                new Random().Next();


            // -------------------------------------------------
            // BASE TERRAIN
            // -------------------------------------------------

            SurfaceHeight =
                100;


            // -------------------------------------------------
            // LARGE HILLS
            // -------------------------------------------------

            HillHeight =
                25;


            HillScale =
                0.003f;


            // -------------------------------------------------
            // MEDIUM TERRAIN
            // -------------------------------------------------

            TerrainVariation =
                10;


            TerrainScale =
                0.012f;


            // -------------------------------------------------
            // SMALL TERRAIN DETAIL
            // -------------------------------------------------

            TerrainDetail =
                3;


            TerrainDetailScale =
                0.035f;

        }

    }

}